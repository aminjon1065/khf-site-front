import type { AlertLevel, RegionKey } from "@/lib/types";

/** Одно предупреждение в разрезе одного затронутого региона. */
export interface LiveIncident {
  kind: string;
  level: AlertLevel;
  time: string;
  title: string;
  region: string;
  regionKey: RegionKey;
  slug: string;
}

/**
 * Свёртка развёрнутых по регионам записей обратно в предупреждения.
 *
 * Карте нужна запись на каждый затронутый регион — иначе нечем красить. А
 * списку справа и счётчику нужна запись на каждое предупреждение. Раньше и
 * там, и там использовался развёрнутый массив: предупреждение по трём
 * регионам давало три одинаковые строки (поле `region` у всех копий одно и то
 * же — это описание из самого предупреждения) и утраивало счётчик.
 * Республиканское предупреждение (`territory_type=country`) разворачивалось на
 * все пять регионов и показывало «5 событий» вместо одного.
 *
 * Порядок сохраняется: первая встреченная запись каждого предупреждения.
 */
export function uniqueAlerts(incidents: LiveIncident[]): LiveIncident[] {
  const seen = new Set<string>();

  // Именно filter, а не `new Map(...).values()`: при повторе ключа Map
  // оставляет последнее значение, и запись получала бы регион последней копии
  // при порядке по первой — рассогласование, которое ловится не сразу.
  return incidents.filter((i) => {
    if (seen.has(i.slug)) {
      return false;
    }
    seen.add(i.slug);

    return true;
  });
}
